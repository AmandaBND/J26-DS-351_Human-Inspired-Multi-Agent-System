
from pathlib import Path

import joblib
import numpy as np
import opensmile


PROJECT_ROOT = Path(__file__).resolve().parents[3]
MODEL_PATH = (
    PROJECT_ROOT
    / "ser_training"
    / "outputs"
    / "ser_model.joblib"
)


class EGeMAPSSERService:
    """Experimental SER using the locally trained eGeMAPS + SVM model."""

    def __init__(self, model_path=MODEL_PATH):
        model_path = Path(model_path)

        if not model_path.exists():
            raise FileNotFoundError(
                f"Trained SER model not found: {model_path}"
            )

        # Load only model files generated by your own training script.
        artifact = joblib.load(model_path)

        self.model = artifact["model"]
        self.feature_columns = artifact["feature_columns"]

        self.smile = opensmile.Smile(
            feature_set=opensmile.FeatureSet.eGeMAPSv02,
            feature_level=opensmile.FeatureLevel.Functionals,
        )

    def analyze(self, customer_segments):
        results = []

        for segment in customer_segments:
            start = float(segment.start_seconds)
            end = float(segment.end_seconds)
            duration = end - start

            if duration < 1.0:
                results.append({
                    "start_seconds": start,
                    "end_seconds": end,
                    "duration_seconds": duration,
                    "predicted_emotion": "Not analyzed",
                    "status": "Too short for experimental SER",
                })
                continue

            try:
                samples = np.asarray(
                    segment.samples,
                    dtype=np.float32,
                )

                features = self.smile.process_signal(
                    samples,
                    sampling_rate=int(segment.sample_rate),
                )

                # Match the exact feature order used during training.
                missing = [
                    col for col in self.feature_columns
                    if col not in features.columns
                ]

                if missing:
                    raise ValueError(
                        f"Missing acoustic features: {missing}"
                    )

                X = features.loc[
                    :, self.feature_columns
                ].to_numpy(dtype=float)

                if not np.isfinite(X).all():
                    raise ValueError(
                        "Non-finite eGeMAPS feature values"
                    )

                prediction = str(self.model.predict(X)[0])

                results.append({
                    "start_seconds": start,
                    "end_seconds": end,
                    "duration_seconds": duration,
                    "predicted_emotion": prediction,
                    "status": "Experimental prediction",
                })

            except Exception as exc:
                results.append({
                    "start_seconds": start,
                    "end_seconds": end,
                    "duration_seconds": duration,
                    "predicted_emotion": "Unavailable",
                    "status": str(exc),
                })

        return results
